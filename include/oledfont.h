/*! \file oledfont.h \brief OLED 精简字库：8x16 ASCII 子集 + 16x16 汉字 x3
 *
 *  【字库设计思路】GD32E230 Flash 只有 64KB，塞不下 GB2312 全字库（~260KB）。
 *  温湿度计场景实际只需要 3 个汉字 —— "按需取模"是资源受限系统的标准做法：
 *  每个汉字 32 字节，3 字共 96 字节；ASCII 只留会用到的 19 个字符。
 *
 *  【取模格式约定】（用 PCtoLCD2002 重新取模时必须选同样的设置）：
 *    阴码（亮点=1）、逐行式、顺向（高位在前 MSB=最左像素）、C51 格式
 *  汉字 16x16：每行 2 字节共 16 行 = 32 字节；字节 f[2r]=行r左8像素、f[2r+1]=行r右8像素
 *  ASCII 8x16：页格式——前 8 字节=上半页（每字节一列，bit0=最上行），后 8 字节=下半页
 *  （两种格式不同：汉字需转置后再上屏，见 oled.c 的 oled_show_hanzi；ASCII 直写）*/
